import { PINS } from "./pins.js";
import { editionMapping, REGISTRY, valueText } from "./registry.js";
import type { StateMapping, Verification } from "./registry-types.js";
import type { Edition } from "./types.js";

const cell = (s: string) => s.replace(/\|/g, "\\|");

function describe(m: StateMapping): string {
  if ("value" in m) return `always \`${JSON.stringify(m.value)}\``;
  return Object.entries(m.map)
    .map(([k, v]) => `${m.from}=${k} → \`${JSON.stringify(v)}\``)
    .join(", ");
}

/**
 * Renders the mapping table (`docs/bedrock-mapping.md` for Bedrock): every abstract type and state with its target
 * ID and state values, the pinned data versions, and what still needs proof in game. `rsd registry dump` prints it.
 */
export function renderMappingDoc(edition: Edition = "bedrock"): string {
  const title = edition === "bedrock" ? "Bedrock" : "Java";
  const lines: string[] = [
    `# ${title} mapping`,
    "",
    "<!-- GENERATED by `rsd registry dump` from packages/core/registry. Do not edit. -->",
    "",
    `Every abstract block type and state, with the ${title} block ID and state values the exporters emit.`,
    "",
    `- Game version: ${PINS.gameVersion}`,
    `- \`@minecraft/vanilla-data\`: ${PINS.vanillaData} (block IDs and state names)`,
    `- Mojang \`bedrock-samples\`: ${PINS.bedrockSamples}, \`metadata/vanilladata_modules/mojang-blocks.json\` (state value domains), SHA-256 \`${PINS.mojangBlocksSha256}\``,
    "",
    "IDs, state names and value domains are checked against those pinned files by the registry tests. What each",
    "value means in game (which number is which direction) cannot be read from them: those rows are marked",
    "VERIFY-IN-GAME and stay unverified (W108) until the M3 orientation test proves them in a world.",
    "",
    "| Type | Abstract states | ID | State mapping | In game |",
    "| --- | --- | --- | --- | --- |",
  ];
  for (const entry of REGISTRY) {
    const mapping = editionMapping(entry, edition);
    const states =
      Object.entries(entry.states)
        .map(
          ([k, d]) =>
            `${k}: ${d.values.map(valueText).join(" / ")} (default ${valueText(d.default)})${d.directional ? ", directional" : ""}`,
        )
        .join("<br>") || "none";
    if (!mapping) {
      lines.push(`| ${entry.type} | ${cell(states)} | not mapped yet | | |`);
      continue;
    }
    const idRule = mapping.id;
    const id =
      typeof idRule === "string"
        ? `\`${idRule}\``
        : Object.entries(idRule.map)
            .map(([k, v]) => `${idRule.from}=${k} → \`${v}\``)
            .join("<br>");
    const stateRows = Object.entries(mapping.states).map(([name, m]) => `\`${name}\`: ${describe(m)}`);
    if (mapping.upper) {
      stateRows.push(
        `upper half at +[${mapping.upper.offset.join(",")}]: ${Object.entries(mapping.upper.states)
          .map(([n, m]) => `\`${n}\` ${describe(m)}`)
          .join(", ")}`,
      );
    }
    const verify = [
      ...Object.entries({ ...mapping.states, ...(mapping.upper?.states ?? {}) })
        .filter(([, m]) => m.verify)
        .map(([, m]) => m.verify ?? ""),
    ];
    const status = entry.verified
      ? `verified ${entry.verified.gameVersion}, ${entry.verified.date}, ${entry.verified.by}`
      : ["not verified (W108)", ...verify].join("<br>");
    lines.push(
      `| ${entry.type} | ${cell(states)} | ${cell(id)} | ${cell(stateRows.join("<br>") || "none")} | ${cell(status)} |`,
    );
  }
  return `${lines.join("\n")}\n`;
}

/**
 * Renders `docs/verify-in-game.md`: every mapping assumption the pinned data cannot prove, with its status. A
 * block's assumptions close when its registry entry gets a `verified` record.
 */
export function renderVerifyLog(
  edition: Edition = "bedrock",
  extra: readonly { area: string; item: string; assumption: string; proven?: Verification }[] = [],
): string {
  const lines = [
    "# VERIFY-IN-GAME log",
    "",
    "<!-- GENERATED by `pnpm docs:gen` from packages/core/registry. Do not edit. -->",
    "",
    "Every Bedrock mapping and exporter assumption that the pinned data cannot prove. A row closes when it is",
    "proven in game: by a `verified` record on the block's registry entry (which also removes W108), or by a",
    "`proven` record on that one state when the rest of the block is not proven yet.",
    "",
    "| ID | Block | State | Assumption | Status |",
    "| --- | --- | --- | --- | --- |",
  ];
  let n = 0;
  for (const entry of REGISTRY) {
    const mapping = editionMapping(entry, edition);
    if (!mapping) continue;
    for (const [name, m] of Object.entries({ ...mapping.states, ...(mapping.upper?.states ?? {}) })) {
      if (!m.verify) continue;
      n++;
      const proof = m.proven ?? entry.verified;
      const status = proof ? `verified ${proof.gameVersion} (${proof.date})` : "open";
      lines.push(
        `| VIG-${String(n).padStart(2, "0")} | ${entry.type} | \`${name}\` | ${cell(m.verify.replace(/^VERIFY-IN-GAME: /, ""))} | ${status} |`,
      );
    }
  }
  for (const row of extra) {
    n++;
    lines.push(
      `| VIG-${String(n).padStart(2, "0")} | ${row.area} | ${cell(row.item)} | ${cell(row.assumption)} | ${row.proven ? `verified ${row.proven.gameVersion} (${row.proven.date})` : "open"} |`,
    );
  }
  lines.push(
    "",
    "Blocks without orientation (stone, glass, wool, lamp, ...) have no rows here but still show W108 until the first",
    "in-game build confirms their IDs.",
  );
  return `${lines.join("\n")}\n`;
}
