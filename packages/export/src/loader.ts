import { diag, isValidSlug, PINS, toEditionBlocks } from "@dustwright/core";
import type { Diagnostic, Model, StateValue } from "@dustwright/core";
import { PACK_VERSION, uuidV5 } from "./manifest.js";
import { placementOrder } from "./mcfunction.js";
import { zipDeterministic } from "./zip.js";

/** One design as the loader stores it: its box and its Bedrock blocks, in the function exporter's order. */
export interface LoaderDesign {
  size: [number, number, number];
  /** [x, y, z, id, states], relative to the design's origin. */
  blocks: [number, number, number, string, Record<string, StateValue>][];
}

/**
 * The loader script (M10, docs/m10-extensions.md): plain JavaScript on the stable `@minecraft/server` API only. It
 * reads designs from `designs.js` in its own pack and, on `/scriptevent rsd:build <slug> <x> <y> <z>`, places
 * their blocks with BlockPermutation; `rsd:clear` with the same arguments empties the design's box, `rsd:list`
 * names the designs. Placement runs as a job, a few blocks per tick, so a large design does not trip the watchdog,
 * and there is no command limit. It evaluates nothing from a design: the designs are data.
 */
export const LOADER_SCRIPT = `// Dustwright loader: builds the designs in designs.js. Generated by \`rsd loader\`.
//   /scriptevent rsd:build <slug> <x> <y> <z>   build a design with its origin at x y z (overworld)
//   /scriptevent rsd:clear <slug> <x> <y> <z>   fill that design's box with air
//   /scriptevent rsd:list                       name the designs in this pack
import { BlockPermutation, system, world } from "@minecraft/server";
import { DESIGNS } from "./designs.js";

const say = (text) => {
  console.warn(\`[rsd] \${text}\`);
  world.sendMessage(\`[rsd] \${text}\`);
};

function* build(slug, design, origin) {
  const dimension = world.getDimension("overworld");
  let placed = 0;
  for (const [x, y, z, id, states] of design.blocks) {
    const block = dimension.getBlock({ x: origin.x + x, y: origin.y + y, z: origin.z + z });
    if (!block) {
      say(\`\${slug}: [\${x},\${y},\${z}] is not loaded; stopped after \${placed} blocks\`);
      return;
    }
    block.setPermutation(BlockPermutation.resolve(id, states));
    placed++;
    yield;
  }
  say(\`built \${slug} (\${placed} blocks)\`);
}

function* clear(slug, design, origin) {
  const dimension = world.getDimension("overworld");
  const [w, h, l] = design.size;
  for (let y = h - 1; y >= 0; y--) {
    for (let z = 0; z < l; z++) {
      for (let x = 0; x < w; x++) {
        const block = dimension.getBlock({ x: origin.x + x, y: origin.y + y, z: origin.z + z });
        if (block) block.setType("minecraft:air");
        yield;
      }
    }
  }
  say(\`cleared \${slug}\`);
}

system.afterEvents.scriptEventReceive.subscribe((event) => {
  if (event.id === "rsd:list") {
    say(Object.keys(DESIGNS).join(", ") || "no designs");
    return;
  }
  if (event.id !== "rsd:build" && event.id !== "rsd:clear") return;
  const [slug, ...coords] = event.message.trim().split(/\\s+/);
  const design = Object.hasOwn(DESIGNS, slug) ? DESIGNS[slug] : undefined;
  const n = coords.map(Number);
  if (!design || n.length !== 3 || !n.every(Number.isInteger)) {
    say(\`usage: /scriptevent \${event.id} <slug> <x> <y> <z>; designs: \${Object.keys(DESIGNS).join(", ")}\`);
    return;
  }
  const origin = { x: n[0], y: n[1], z: n[2] };
  system.runJob(event.id === "rsd:build" ? build(slug, design, origin) : clear(slug, design, origin));
});
`;

/** A design's loader data: its Bedrock blocks with their offsets (a door's upper half), in placement order. */
export function loaderDesign(model: Model): LoaderDesign {
  const blocks: LoaderDesign["blocks"] = [];
  const size: [number, number, number] = [...model.size];
  for (const { key, pos } of placementOrder(model)) {
    const block = model.blocks.get(key);
    if (!block) continue;
    for (const b of toEditionBlocks(block, "bedrock")) {
      const p: [number, number, number] = [pos[0] + b.offset[0], pos[1] + b.offset[1], pos[2] + b.offset[2]];
      for (let i = 0; i < 3; i++) size[i] = Math.max(size[i] ?? 0, (p[i] ?? 0) + 1);
      blocks.push([p[0], p[1], p[2], b.id, b.states]);
    }
  }
  return { size, blocks };
}

/** The designs module: one exported JSON literal (data only; JSON is a subset of JavaScript). */
export function loaderDesignsModule(models: readonly Model[]): string {
  const designs = Object.fromEntries(models.map((m) => [m.meta.slug, loaderDesign(m)]));
  return `// Generated by \`rsd loader\`: designs as data, Bedrock blocks in placement order.\nexport const DESIGNS = ${JSON.stringify(designs)};\n`;
}

/** The loader pack's manifest: one script module on the pinned stable `@minecraft/server`. */
export async function loaderManifest(slugs: readonly string[]): Promise<string> {
  const id = `loader:${[...slugs].sort().join(",")}`;
  const engine = PINS.gameVersion.split(".").map(Number);
  return `${JSON.stringify(
    {
      format_version: 2,
      header: {
        name: "Dustwright loader",
        description: `Builds ${slugs.length} redstone design(s) with /scriptevent rsd:build <slug> <x> <y> <z>.`,
        uuid: await uuidV5(id),
        version: PACK_VERSION,
        min_engine_version: engine,
      },
      modules: [
        {
          type: "script",
          language: "javascript",
          entry: "scripts/main.js",
          uuid: await uuidV5(`${id}/script`),
          version: PACK_VERSION,
        },
      ],
      dependencies: [{ module_name: "@minecraft/server", version: PINS.scriptApiServer }],
    },
    null,
    2,
  )}\n`;
}

/** The result of building a loader pack. */
export interface LoaderPackResult {
  bytes?: Uint8Array;
  diagnostics: Diagnostic[];
}

/**
 * `rsd loader`: one behavior pack (`.mcpack`) holding the loader script and the given Bedrock designs. Slugs must
 * be valid and distinct; deterministic for identical input.
 */
export async function buildLoaderPack(models: readonly Model[]): Promise<LoaderPackResult> {
  const diagnostics: Diagnostic[] = [];
  const seen = new Set<string>();
  for (const m of models) {
    if (m.meta.edition !== "bedrock")
      throw new Error(`the loader is a Bedrock add-on; ${m.meta.slug} is ${m.meta.edition}`);
    if (!isValidSlug(m.meta.slug))
      diagnostics.push(diag("E012", `Slug "${m.meta.slug}" is not valid`, { path: "/meta/slug" }));
    if (seen.has(m.meta.slug))
      diagnostics.push(
        diag("E012", `Two designs share the slug "${m.meta.slug}"`, {
          path: "/meta/slug",
          hint: "Give one a different meta.slug.",
        }),
      );
    seen.add(m.meta.slug);
  }
  if (diagnostics.length > 0) return { diagnostics };
  const enc = (s: string) => new TextEncoder().encode(s);
  const bytes = zipDeterministic({
    "manifest.json": enc(await loaderManifest(models.map((m) => m.meta.slug))),
    "scripts/main.js": enc(LOADER_SCRIPT),
    "scripts/designs.js": enc(loaderDesignsModule(models)),
  });
  return { bytes, diagnostics };
}
